JUMP_GET_WIP = """
SELECT SERIAL_NUMBER, LINE_NAME, GROUP_NAME, SECTION_NAME, STATION_NAME, ERROR_FLAG, SPECIAL_ROUTE
FROM SFISM4.R_WIP_TRACKING_T WHERE SERIAL_NUMBER = :sn
"""

JUMP_GET_ROUTE_LIST = """
SELECT T1.STEP_SEQUENCE AS STEP, T1.GROUP_NAME, T1.GROUP_NEXT, T1.STATE_FLAG AS FLAG
FROM SFIS1.C_ROUTE_CONTROL_T T1, SFISM4.R_WIP_TRACKING_T T2
WHERE T1.ROUTE_CODE = T2.SPECIAL_ROUTE AND T2.SERIAL_NUMBER = :sn AND T1.STATE_FLAG = '0'
ORDER BY T1.STEP_SEQUENCE
"""

JUMP_CHECK_JUMP_STATION = """
SELECT * FROM (
    WITH TEMP_ROUTE AS (
        SELECT ROUTE_CODE, GROUP_NAME, GROUP_NEXT, STEP_SEQUENCE
        FROM SFIS1.C_ROUTE_CONTROL_T WHERE STATE_FLAG = '0'
        AND ROUTE_CODE = (SELECT SPECIAL_ROUTE FROM SFISM4.R_WIP_TRACKING_T WHERE SERIAL_NUMBER = :sn)
        ORDER BY STEP_SEQUENCE
    ),
    TEMP_KITTING AS (
        SELECT ROUTE_CODE, GROUP_NAME, STEP_SEQUENCE FROM TEMP_ROUTE
        WHERE GROUP_NAME IN (SELECT GROUP_NAME FROM SFIS1.KITTING_GROUP_V)
    ),
    TEMP_TARGET AS (
        SELECT GROUP_NAME AS TARGET_GROUP, STEP_SEQUENCE AS TARGET_SEQ FROM TEMP_ROUTE WHERE GROUP_NAME = :g
    )
    SELECT * FROM TEMP_KITTING T1 LEFT JOIN TEMP_TARGET T2 ON 1=1 WHERE T2.TARGET_SEQ > T1.STEP_SEQUENCE
)
"""

JUMP_CHECK_ASSY = """
SELECT COUNT(0) AS CNT FROM SFISM4.R_ASSY_COMPONENT_T
WHERE ASSY_FLAG = 'Y' AND SERIAL_NUMBER = :sn AND GROUP_NAME = :g
"""
