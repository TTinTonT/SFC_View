KITTING_FETCH_ASSY_TREE = """
SELECT
    SERIAL_NUMBER AS SN,
    FATHER_SN,
    SUB_MODEL_NAME,
    MODEL_NAME,
    VENDOR_SN,
    TO_CHAR(
        (FROM_TZ(CAST(IN_STATION_TIME AS TIMESTAMP), SESSIONTIMEZONE) AT TIME ZONE 'America/Los_Angeles'),
        'YYYY-MM-DD HH24:MI:SS'
    ) AS IN_STATION_TIME,
    STACK,
    ASSY_FLAG,
    ASSY_SEQ
FROM SFISM4.R_ASSY_COMPONENT_T
WHERE SERIAL_NUMBER = :sn
  AND GROUP_NAME IN (SELECT GROUP_NAME FROM SFIS1.KITTING_GROUP_V)
ORDER BY ASSY_SEQ, VENDOR_SN
"""

KITTING_COUNT_DEKITTED = """
SELECT COUNT(*) FROM SFISM4.R_ASSY_COMPONENT_T
WHERE SERIAL_NUMBER = :sn AND ASSY_FLAG = 'N'
  AND GROUP_NAME IN (SELECT GROUP_NAME FROM SFIS1.KITTING_GROUP_V)
"""

KITTING_DEKIT_UPDATE = """
UPDATE SFISM4.R_ASSY_COMPONENT_T
SET ASSY_FLAG = 'N', IN_STATION_TIME = SYSDATE, EMP_NO = :emp
WHERE SERIAL_NUMBER = :sn AND ASSY_FLAG = 'Y' AND VENDOR_SN = :v
  AND (FATHER_SN = :f OR (FATHER_SN IS NULL AND :f IS NULL))
"""

KITTING_INSERT_SELECT = """
SELECT * FROM SFISM4.R_ASSY_COMPONENT_T
WHERE SERIAL_NUMBER = :sn AND VENDOR_SN = :old
  AND (FATHER_SN = :old_f OR (FATHER_SN IS NULL AND :old_f IS NULL))
  AND ASSY_FLAG = 'N'
ORDER BY IN_STATION_TIME DESC
"""

KITTING_CHECK_VENDOR_IN_OTHER_TRAY = """
SELECT SERIAL_NUMBER AS TRAY_SN,
       VENDOR_SN,
       FATHER_SN,
       SUB_MODEL_NAME,
       IN_STATION_TIME,
       GROUP_NAME
FROM SFISM4.R_ASSY_COMPONENT_T
WHERE VENDOR_SN = :vendor_sn
  AND ASSY_FLAG = 'Y'
  AND GROUP_NAME IN (SELECT GROUP_NAME FROM SFIS1.KITTING_GROUP_V)
  AND SERIAL_NUMBER != :current_sn
"""
