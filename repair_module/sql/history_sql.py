REPAIR_FAIL_HISTORY = """
SELECT SERIAL_NUMBER, TEST_TIME, REPAIR_TIME, GROUP_NAME, RECORD_TYPE,
       ERROR_CODE_IN_REPAIR, ERROR_CODE_MASTER, ERROR_DESC
FROM (
    SELECT
        r.SERIAL_NUMBER,
        r.TEST_TIME,
        r.REPAIR_TIME,
        r.GROUP_NAME,
        r.RECORD_TYPE,
        r.TEST_CODE AS ERROR_CODE_IN_REPAIR,
        e.ERROR_CODE AS ERROR_CODE_MASTER,
        e.ERROR_DESC,
        ROW_NUMBER() OVER (
            PARTITION BY REPLACE(NVL(r.TEST_CODE, ' '), ' ', '')
            ORDER BY NVL(r.REPAIR_TIME, r.TEST_TIME) DESC NULLS LAST, r.TEST_TIME DESC NULLS LAST
        ) AS rn
    FROM SFISM4.R_REPAIR_T r
    LEFT JOIN SFIS1.C_ERROR_CODE_T e
           ON REPLACE(e.ERROR_CODE, ' ', '') = REPLACE(r.TEST_CODE, ' ', '')
    WHERE r.SERIAL_NUMBER = :sn
)
WHERE rn = 1
ORDER BY NVL(REPAIR_TIME, TEST_TIME) ASC NULLS LAST
"""
